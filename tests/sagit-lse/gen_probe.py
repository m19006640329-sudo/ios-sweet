#!/usr/bin/env python3
"""Emit real LSE instruction words and the semantics they should decode to.

Hand-written bit patterns would only test the decoder against my reading of
the ARM ARM.  Instead the system assembler encodes every helper's mnemonic
(-march=armv8.1-a), and the words are handed to the test, which must recover
the same (op, size, ordering, is-ST) tuple and emulate the instruction
correctly.

Instruction selection: Rt_Wt = w6, Rs = w5 (compare value for CAS), Xn = x7.
"""

import argparse
import os
import struct
import subprocess
import sys

OPS = [('add', 0), ('clr', 1), ('eor', 2), ('set', 3),
       ('smax', 4), ('smin', 5), ('umax', 6), ('umin', 7)]
SIZES = [(0, 'b', 'w'), (1, 'h', 'w'), (2, '', 'w'), (3, '', 'x')]
ORDS = [(0, ''), (1, 'a'), (2, 'l'), (3, 'al')]


def insns():
    """(text, op, size, ord, is_st) in emission order."""
    out = []
    for name, op in OPS:
        for sz, ssfx, rk in SIZES:
            for od, osfx in ORDS:
                out.append(('%s%s%s %s5, %s6, [x7]' % ('ld' + name, osfx, ssfx, rk, rk),
                            op, sz, od, 0))
            for od, osfx in [(0, ''), (2, 'l')]:
                out.append(('%s%s%s %s5, [x7]' % ('st' + name, osfx, ssfx, rk),
                            op, sz, od, 1))
    for sz, ssfx, rk in SIZES:
        for od, osfx in ORDS:
            out.append(('swp%s%s %s5, %s6, [x7]' % (osfx, ssfx, rk, rk), 8, sz, od, 0))
            out.append(('cas%s%s %s5, %s6, [x7]' % (osfx, ssfx, rk, rk), 9, sz, od, 0))
    return out


def elf_text(path):
    data = open(path, 'rb').read()
    if data[:4] != b'\x7fELF' or data[4] != 2 or data[5] != 1:
        sys.exit('%s: not a 64-bit little-endian ELF' % path)
    shoff, = struct.unpack_from('<Q', data, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', data, 0x3A)
    secs = []
    for i in range(shnum):
        off = shoff + i * shentsize
        name, _typ = struct.unpack_from('<II', data, off)
        _flags, _addr, offset, size = struct.unpack_from('<QQQQ', data, off + 8)
        secs.append((name, offset, size))
    strtab = secs[shstrndx][1]

    def sname(idx):
        end = data.index(b'\0', strtab + idx)
        return data[strtab + idx:end].decode()

    for name, offset, size in secs:
        if sname(name) == '.text':
            return data[offset:offset + size]
    sys.exit('%s: no .text section' % path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--clang', default='clang')
    ap.add_argument('--work', required=True)
    ap.add_argument('--out', required=True)
    args = ap.parse_args()

    items = insns()
    src = os.path.join(args.work, 'lse_probe.s')
    obj = os.path.join(args.work, 'lse_probe.o')
    with open(src, 'w', encoding='utf-8') as f:
        f.write('\t.text\n\t.globl probe_start\nprobe_start:\n')
        for text, _op, _sz, _od, _st in items:
            f.write('\t%s\n' % text)

    cmd = [args.clang, '--target=aarch64-none-elf', '-march=armv8.1-a', '-c', src, '-o', obj]
    res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if res.returncode != 0:
        sys.exit('assembling LSE probes failed:\n' + res.stdout.decode('utf-8', 'replace'))

    text = elf_text(obj)
    if len(text) != 4 * len(items):
        sys.exit('probe .text is %d bytes, expected %d' % (len(text), 4 * len(items)))
    words = struct.unpack('<%dI' % len(items), text)

    body = '\n'.join('\t{ 0x%08xu, %d, %d, %d, %d },' % (w, op, sz, od, st)
                     for w, (_t, op, sz, od, st) in zip(words, items))
    with open(args.out, 'w', encoding='utf-8') as f:
        f.write('/* Generated by gen_probe.py from assembler output.  Do not edit. */\n')
        f.write('static const struct probe probes[] = {\n%s\n};\n' % body)


if __name__ == '__main__':
    main()
